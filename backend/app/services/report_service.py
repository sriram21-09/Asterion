class ReportBuilder:
    def __init__(self, db: Session, case_id: int):
        case = CaseRepository.get(db, case_id=case_id)
        if not case:
            raise HTTPException(status_code=404, detail="Case not found")
        self.ctx = ReportContext(db, case)
        self.story: list[Any] = []

    def build_report(self, report_type: str):
        # Assemble 4-page target layout cleanly
        self.story.extend(SectionFactory.build_header_and_overview(self.ctx))
        self.story.append(PageBreak())
        self.story.extend(SectionFactory.build_localization_assessment(self.ctx))
        self.story.append(PageBreak())
        self.story.extend(SectionFactory.build_evidence_provenance(self.ctx))
        self.story.append(PageBreak())
        self.story.extend(SectionFactory.build_conclusions_and_appendix(self.ctx))

        return self

    def render(self) -> str:
        report_dir = os.path.abspath(
            os.path.join(os.path.dirname(__file__), "..", "..", "data", "reports")
        )
        os.makedirs(report_dir, exist_ok=True)
        filename = f"report_case_{self.ctx.case.id}_{uuid.uuid4().hex[:8]}.pdf"
        filepath = os.path.join(report_dir, filename)

        doc = SimpleDocTemplate(
            filepath,
            pagesize=letter,
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=54,
        )
        doc.build(self.story, canvasmaker=NumberedCanvas)
        return filepath


